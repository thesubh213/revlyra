export type SignalCode = (typeof CODES)[keyof typeof CODES];

export const ALL_SIGNAL_CODES: SignalCode[] = Object.values(CODES);

export function isSignalCode(value: string): value is SignalCode {
  return (ALL_SIGNAL_CODES as string[]).includes(value);
}

